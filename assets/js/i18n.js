export function getLang() {
  const urlParam = new URLSearchParams(window.location.search).get('lang');
  if (urlParam === 'so' || urlParam === 'en') {
    localStorage.setItem('adde_lang', urlParam);
    return urlParam;
  }
  return localStorage.getItem('adde_lang') || 'en';
}

export function setLang(lang) {
  const safe = lang === 'so' ? 'so' : 'en';
  localStorage.setItem('adde_lang', safe);
  applyTranslations(safe);
  window.dispatchEvent(new CustomEvent('adde:langchange', { detail: { lang: safe } }));
}

export function applyTranslations(lang = getLang()) {
  const dict = DICTIONARY[lang] || DICTIONARY.en;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });
  document.querySelectorAll('.lang-btn-en').forEach((b) => b.classList.toggle('active', lang === 'en'));
  document.querySelectorAll('.lang-btn-so').forEach((b) => b.classList.toggle('active', lang === 'so'));
}
